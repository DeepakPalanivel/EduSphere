// ─── SEED FUNCTION ────────────────────────────────────────────────────────────

async function seed() {
  const uri = process.env.MONGO_URI || 'mongodb://localhost:27017/campusone';
  await mongoose.connect(uri);
  console.log('Connected to MongoDB');

  await Promise.all([
    User.deleteMany({}),
    StudyMaterial.deleteMany({}),
    Software.deleteMany({}),
  ]);
  console.log('Cleared existing data');

  const admin = await User.create({
    fullName: 'Admin User',
    email: 'admin@edusphere.edu',
    password: 'Admin@123',
    role: 'admin',
    department: 'Administration',
    course: 'N/A',
    yearOfStudy: 1,
  });
  console.log('Admin created: admin@edusphere.edu / Admin@123');

  const student = await User.create({
    fullName: 'Priya Sharma',
    email: 'priya@student.edu',
    password: 'Student@123',
    role: 'student',
    department: 'Computer Science',
    course: 'B.Tech',
    yearOfStudy: 3,
  });
  console.log('Student created: priya@student.edu / Student@123');

  await Software.insertMany(softwareData.map(s => ({ ...s, addedBy: admin._id })));
  console.log(`Seeded ${softwareData.length} software entries`);

  await StudyMaterial.insertMany(materialData.map(m => ({ ...m, uploader: student._id, isApproved: true })));
  console.log(`Seeded ${materialData.length} study materials`);

  console.log('\n✅ Seed complete!');
  console.log(`   Software:  ${softwareData.length} entries`);
  console.log(`   Materials: ${materialData.length} entries (includes question papers)`);
  console.log('\n   Admin login:   admin@edusphere.edu / Admin@123');
  console.log('   Student login: priya@student.edu  / Student@123');
  await mongoose.disconnect();
}

seed().catch(err => {
  console.error('Seed failed:', err);
  process.exit(1);
});
